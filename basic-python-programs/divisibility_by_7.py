#A program to ask a number from user and check whether it is divisible by 7 or not.

a=int(input("Enter 1st number : "))
b=int(input("Enter 2nd number : "))
if a%7 == 0:
    print(a,"is divisible by 7")
else:
    print(a,"is not divisible by 7")
if b%7 == 0:
    print(b,"is divisible by 7")
else:
    print(b,"is not divisible by 7")
